// Builds src/styles/fa-icons.css from the SVGs in src/icons.
//
// The app used to ship the whole Font Awesome font set for ~80 icons. Templates still
// say `<i class="fa-solid fa-trash">` (many pick the class at runtime, and the e2e
// specs select on it), so instead of changing them each `fa-*` class is defined here
// as a CSS mask over an inline SVG. The icons keep following `color` and `font-size`.
//
// To add an icon: copy its SVG from Font Awesome Free into src/icons/<style>/, add the
// class name to src/icons/icons.json, then run `pnpm icons`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src");
const STYLES = ["solid", "regular", "brands"];

const header = `/*
 * GENERATED by scripts/build-icons.mjs from src/icons -- edit icons.json, not this file.
 *
 * Icons: Font Awesome Free 7.3.1 by @fontawesome - https://fontawesome.com
 * License: CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/), Copyright 2026 Fonticons, Inc.
 */
`;

const base = `
.fa,
.fas,
.fa-solid,
.far,
.fa-regular,
.fab,
.fa-brands {
  display: inline-block;
  width: 1.25em;
  font-style: normal;
  line-height: 1;
  text-align: center;
}

/*
 * Fixed 1.25em width and centred glyph, as Font Awesome 7 sets them. The glyph lives in
 * ::before, like the font's did, so utilities on the element itself (a background,
 * padding, a border) still style the element rather than the icon.
 */
.fa::before,
.fas::before,
.fa-solid::before,
.far::before,
.fa-regular::before,
.fab::before,
.fa-brands::before {
  content: "";
  /* Inline, on the baseline, so the element's line-height shapes the box as it did for a glyph. */
  display: inline-block;
  vertical-align: -0.125em;
  /* The glyph is as wide as its icon (viewBox width over its 512 height), centred in the 1.25em element. */
  width: calc(var(--fa-w) * 1em);
  height: 1em;
  background-color: currentColor;
  -webkit-mask-image: var(--fa-icon);
  mask-image: var(--fa-icon);
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-position: center;
  mask-position: center;
  -webkit-mask-size: contain;
  mask-size: contain;
}

.fa-spin {
  animation: fa-spin 2s linear infinite;
}

@keyframes fa-spin {
  to {
    transform: rotate(360deg);
  }
}

@media (prefers-reduced-motion: reduce) {
  .fa-spin {
    animation-duration: 1ms;
    animation-iteration-count: 1;
  }
}
`;

function dataUri(svg) {
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim()
    .replace(/"/g, "'")
    .replace(/%/g, "%25")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .replace(/#/g, "%23");
  return `url("data:image/svg+xml,${body}")`;
}

/** Returns the stylesheet for the icons listed in src/icons/icons.json. */
export function buildCss(srcDir = root) {
  const map = JSON.parse(fs.readFileSync(path.join(srcDir, "icons/icons.json"), "utf8"));
  const rules = [];
  for (const style of STYLES) {
    // Aliases (fa-sync and fa-arrows-rotate) share one rule, and so one copy of the SVG.
    const byFile = new Map();
    for (const [cls, file] of Object.entries(map[style] ?? {})) {
      // The qualified selector keeps a regular or brands icon from being claimed by
      // a solid one of the same name, and outranks the plain `.fa-<name>` rule.
      const selector = style === "solid" ? `.fa-${cls}` : `.fa-${style}.fa-${cls}`;
      byFile.set(file, [...(byFile.get(file) ?? []), selector]);
    }
    for (const [file, selectors] of [...byFile].sort(([a], [b]) => a.localeCompare(b))) {
      const svg = fs.readFileSync(path.join(srcDir, "icons", style, `${file}.svg`), "utf8");
      const width = Number(/viewBox="0 0 (\d+) 512"/.exec(svg)?.[1]);
      if (!width) throw new Error(`${style}/${file}.svg: expected a "0 0 <width> 512" viewBox`);
      rules.push(`${selectors.sort().join(",\n")} {\n  --fa-w: ${width / 512};\n  --fa-icon: ${dataUri(svg)};\n}`);
    }
  }
  return `${header}${base}\n${rules.join("\n\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, "styles/fa-icons.css"), buildCss());
}
